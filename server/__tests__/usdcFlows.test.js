describe('deposit scan + credit loop /api/usdc/check (fully simulated chain)', () => {
    test('credits a confirmed transfer: atomic increment + deposit transaction + notification', async () => {
        const head = 5414;
        const safeHead = head - CONFIRMATIONS; // 5402
        scriptFetch({
            eth_blockNumber: [hex(head)],
            eth_getLogs: [[fakeLog({ to: MY_ADDRESS, amountUnits: 1500000, txHash: TX1, logIndex: 5, blockHex: hex(5320) })]],
        });
        const res = await call(depositsRouter, 'post', '/api/usdc/check', mkReq.post({ network: 'base' }));
        expect(res.code).toBe(200);
        expect(res.body.credited).toEqual([{ amount: 1.5, txHash: TX1, network: 'base', token: 'USDC' }]);
        const upd = CDB.db.query.mock.calls.find((c) => String(c[0]).includes('UPDATE accounts SET balance = balance +'));
        expect(upd[1]).toEqual([ACCOUNT_ID, 1.5]);
        expect(String(upd[0])).toContain('WHERE id = $1');
        expect(CDB.createTransaction.mock.calls[0][0].type).toBe('deposit');
        expect(CDB.createTransaction.mock.calls[0][0].external_reference).toBe(TX1 + ':5');
        expect(CDB.createNotification).toHaveBeenCalledTimes(1);
        const st = CDB.db.query.mock.calls.find((c) => String(c[0]).includes('INSERT INTO usdc_scan_state'));
        expect(String(st[0])).toContain('GREATEST');
        expect(st[1]).toEqual(['base', safeHead]); // scan state advances to safe head only
    });

    test('duplicate deposit (same txHash:logIndex already credited) is skipped - no double credit', async () => {
        const head = 5414;
        scriptFetch({
            eth_blockNumber: [hex(head)],
            eth_getLogs: [[
                fakeLog({ to: OTHER_ADDRESS, amountUnits: 7000000, txHash: TX2, logIndex: 8, blockHex: hex(5320) }), // foreign -> byAddr guard
                fakeLog({ to: MY_ADDRESS, amountUnits: 2000000, txHash: TX2, logIndex: 2, blockHex: hex(5320) }),
                fakeLog({ to: MY_ADDRESS, amountUnits: 1500000, txHash: TX1, logIndex: 5, blockHex: hex(5320) }),
            ]],
        });
        CDB.db.query.mockImplementation(async (sql, params) => {
            const s = String(sql);
            if (s.includes('SELECT id FROM transactions WHERE external_reference')) {
                return { rows: String(params[0]).includes(TX2 + ':2') ? [{ id: 'dup' }] : [] };
            }
            for (const [needle, resp] of defaultDbPairs()) {
                if (s.includes(needle)) { const v = resp(); return v === undefined ? { rows: [] } : v; }
            }
            throw new Error('UNEXPECTED SQL: ' + s.slice(0, 80));
        });
        const res = await call(depositsRouter, 'post', '/api/usdc/check', mkReq.post({ network: 'base' }));
        expect(res.code).toBe(200);
        expect(res.body.credited).toHaveLength(1);           // only TX1 credited
        expect(res.body.credited[0].txHash).toBe(TX1);
        const creditCalls = CDB.db.query.mock.calls.filter((c) => String(c[0]).includes('UPDATE accounts SET balance = balance +'));
        expect(creditCalls).toHaveLength(1);                 // single atomic increment
        expect(CDB.createTransaction.mock.calls[0][0].amount).toBe(1.5);
    });

    test('confirmations gate: scans only the safeHead window; never past it', async () => {
        const head = 100; // 100 - 12 = 88 < fromBlock 90 -> no logging window
        scriptDb(defaultDbPairs().map(([k, f]) => [k, k === 'usdc_scan_state WHERE network' ? () => ({ rows: [{ last_block: 90 }] }) : f]));
        scriptFetch({ eth_blockNumber: [hex(head)], eth_getLogs: [[fakeLog({ to: MY_ADDRESS, amountUnits: 1, txHash: TX1, logIndex: 0, blockHex: hex(99) })]] });
        const res = await call(depositsRouter, 'post', '/api/usdc/check', mkReq.post({ network: 'base' }));
        expect(res.code).toBe(200);
        expect(res.body.credited).toEqual([]);
        expect(fetchCalls.filter((f) => f.method === 'eth_getLogs')).toHaveLength(0);
        // scan state must not advance beyond the queried fromBlock
        const st = CDB.db.query.mock.calls.find((c) => String(c[0]).includes('INSERT INTO usdc_scan_state'));
        expect(st[1]).toEqual(['base', 90]);
    });

    test('direct scanDeposits: scan layer returns every parsed transfer (route layer filters by owned address); zero-amount rejected', async () => {
        const head = 5414;
        const safeHead = head - CONFIRMATIONS;
        scriptFetch({
            eth_blockNumber: [hex(head)],
            eth_getLogs: [[
                fakeLog({ to: OTHER_ADDRESS, amountUnits: 99000000, txHash: TX1, logIndex: 9, blockHex: hex(5320) }), // foreign
                fakeLog({ to: MY_ADDRESS, amountUnits: 2500000, txHash: TX1, logIndex: 3, blockHex: hex(5320) }),
            ]],
        });
        const { transfers, latest } = await scanDeposits('base', [MY_ADDRESS], 90);
        expect(latest).toBe(safeHead);
        expect(transfers).toEqual([
            { to: OTHER_ADDRESS, amount: 99, txHash: TX1, blockNumber: 5320, logIndex: 9 }, // route's byAddr map must catch this one
            { to: MY_ADDRESS, amount: 2.5, txHash: TX1, blockNumber: 5320, logIndex: 3 },
        ]);
        // getLogs per address walks the window in bounded 120-block chunks
        // (public-RPC payload caps); every chunk targets the Base USDC contract:
        const l = fetchCalls.filter((f) => f.method === 'eth_getLogs');
        expect(l).toHaveLength(Math.ceil((safeHead - 90 + 1) / 120));
        expect(parseTransferLog({ topics: [TOPIC, '0', '0'], data: '0x0' }, 6)).toBeNull(); // zero-amount rejected
    });

    test('first scan backfills a bounded window (2000 blocks) via currentHead', async () => {
        const head = 5414;
        // empty scan state -> route derives fromBlock = currentHead - 2000
        scriptDb(defaultDbPairs().map(([k, f]) => [k, k === 'usdc_scan_state WHERE network' ? () => ({ rows: [{ last_block: 0 }] }) : f]));
        scriptFetch({
            eth_blockNumber: [hex(head), hex(head)], // currentHead + scanDeposits
            eth_getLogs: [[fakeLog({ to: MY_ADDRESS, amountUnits: 1000000, txHash: TX1, logIndex: 1, blockHex: hex(5320) })]],
        });
        const res = await call(depositsRouter, 'post', '/api/usdc/check', mkReq.post({ network: 'base' }));
        expect(res.code).toBe(200);
        expect(res.body.credited).toHaveLength(1);
        const l = fetchCalls.filter((f) => f.method === 'eth_getLogs');
        // bounded backfill (head-2000 .. head-CONFIRMATIONS) walked in 120-block chunks
        expect(l).toHaveLength(Math.ceil((head - CONFIRMATIONS - (head - 2000) + 1) / 120));
    });

    test('unknown network in check body -> 400 before any chain call', async () => {
        const res = await call(depositsRouter, 'post', '/api/usdc/check', mkReq.post({ network: 'sepolia' }));
        expect(res.code).toBe(400);
        expect(fetchCalls).toHaveLength(0);
    });

    test('chain-id contract: base answers 0x2105 (8453) -> ok; a misconfigured L1 node is detected', async () => {
        scriptFetch({ eth_chainId: ['0x2105'] });
        expect(await checkChainId('base')).toBe(true);
        scriptFetch({ eth_chainId: ['0x1'] });
        expect(await checkChainId('base')).toBe(false);
    });

    test('every RPC call went to one of the configured public-node URLs only', async () => {
        const head = 5414;
        scriptFetch({ eth_blockNumber: [hex(head)], eth_getLogs: [[]] });
        await call(depositsRouter, 'post', '/api/usdc/check', mkReq.post({ network: 'base' }));
        for (const f of fetchCalls) expect(rpcUrls).toContain(f.url);
    });
});

describe('chain withdrawal /api/usdc/withdraw (fully simulated broadcast)', () => {
    test('happy path: atomic debit -> record -> broadcast; ledger entry carries the external txHash', async () => {
        const res = await call(withdrawalsRouter, 'post', '/api/usdc/withdraw', mkReq.post({ network: 'base', token: 'usdc', to: DEST_ADDRESS, amount: 1 }));
        expect(res.body.success).toBe(true);
        expect(res.body.txHash).toBe(WTX);
        expect(res.body.balance).toBe(999); // parseFloat of RETURNING balance (NUMERIC text)
        const debit = CDB.db.query.mock.calls.find((c) => String(c[0]).includes('UPDATE accounts SET balance = balance -'));
        expect(String(debit[0])).toContain('WHERE id = $1 AND balance >= $2'); // atomic guard
        expect(debit[1]).toEqual([ACCOUNT_ID, 1]);
        expect(CDB.createTransaction.mock.calls[0][0]).toMatchObject({ type: 'withdrawal', amount: -1, external_reference: WTX });
        const calls = CDB.db.query.mock.calls.map((c) => String(c[0]));
        expect(calls.findIndex((s) => s.includes('balance = balance -'))).toBeLessThan(calls.findIndex((s) => s.includes('INSERT INTO usdc_withdrawals')));
        expect(chain.sendTokens).toHaveBeenCalledWith('base', 'usdc', HOT_KEY, HOT_ADDR, DEST_ADDRESS, 1000000n); // exactly 1.00 USDC in 6dp units
    });

    test('broadcast failure: auto-refund + row marked failed + 502, refund AFTER the debit', async () => {
        chain.sendTokens.mockRejectedValue(new Error('nonce too low'));
        const res = await call(withdrawalsRouter, 'post', '/api/usdc/withdraw', mkReq.post({ network: 'base', token: 'usdc', to: DEST_ADDRESS, amount: 1 }));
        expect(res.code).toBe(502);
        expect(res.body.code).toBe('BROADCAST_FAILED');
        const refunds = CDB.db.query.mock.calls.filter((c) => String(c[0]).includes('SET balance = balance +'));
        expect(refunds).toHaveLength(1);
        expect(String(refunds[0][0])).toContain('WHERE id = $1');
        expect(refunds[0][1]).toEqual([ACCOUNT_ID, 1]);
        const failed = CDB.db.query.mock.calls.find((c) => String(c[0]).includes(`SET status = 'failed'`));
        expect(failed[1]).toEqual(['w1']);
        const order = CDB.db.query.mock.calls.map((c) => String(c[0]));
        expect(order.findIndex((s) => s.includes('balance = balance -'))).toBeLessThan(order.findIndex((s) => s.includes('SET balance = balance +')));
        expect(CDB.createTransaction).not.toHaveBeenCalled(); // no phantom ledger entry
    });

    test('insufficient VaultBank balance: guarded UPDATE returns no row -> 400 INSUFFICIENT_FUNDS, nothing broadcast', async () => {
        scriptDb([
            ['COALESCE(SUM(amount), 0)', () => ({ rows: [{ total: '0' }] })],
            ['UPDATE accounts SET balance = balance -', () => ({ rows: [] })],
        ]);
        const res = await call(withdrawalsRouter, 'post', '/api/usdc/withdraw', mkReq.post({ network: 'base', token: 'usdc', to: DEST_ADDRESS, amount: 1 }));
        expect(res.code).toBe(400);
        expect(res.body.code).toBe('INSUFFICIENT_FUNDS');
        expect(chain.sendTokens).not.toHaveBeenCalled();
        expect(CDB.db.query.mock.calls.filter((c) => String(c[0]).includes('INSERT INTO usdc_withdrawals'))).toHaveLength(0);
    });

    test('daily per-user limit enforced before any debit', async () => {
        scriptDb([
            ['COALESCE(SUM(amount), 0)', () => ({ rows: [{ total: '9999.51' }] })],
        ]);
        const res = await call(withdrawalsRouter, 'post', '/api/usdc/withdraw', mkReq.post({ network: 'base', token: 'usdc', to: DEST_ADDRESS, amount: 1 }));
        expect(res.code).toBe(400);
        expect(res.body.code).toBe('DAILY_LIMIT');
        expect(chain.sendTokens).not.toHaveBeenCalled();
    });

    test('wrong network / wrong token / malformed destination -> 400 with zero cascade', async () => {
        const w = (body) => call(withdrawalsRouter, 'post', '/api/usdc/withdraw', mkReq.post(body));
        const bad = await w({ network: 'sepolia', token: 'usdc', to: DEST_ADDRESS, amount: 1 });
        const badToken = await w({ network: 'base', token: 'celr', to: DEST_ADDRESS, amount: 1 });
        const badAddr = await w({ network: 'base', token: 'usdc', to: '0x123', amount: 1 });
        expect(bad.code).toBe(400);
        expect(badToken.code).toBe(400);
        expect(badAddr.code).toBe(400);
        expect(badToken.body.message).toContain('Unknown token');
        expect(badAddr.body.message).toContain('Invalid destination');
        expect(chain.sendTokens).not.toHaveBeenCalled();
    });

    test('signer absent -> 503 not-configured (no key material touched anywhere)', async () => {
        chain.getHotWallet.mockReturnValue(null);
        const res = await call(withdrawalsRouter, 'post', '/api/usdc/withdraw', mkReq.post({ network: 'base', token: 'usdc', to: DEST_ADDRESS, amount: 1 }));
        expect(res.code).toBe(503);
        expect(res.body.code).toBe('USDC_WITHDRAWALS_NOT_CONFIGURED');
    });
});

