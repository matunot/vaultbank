function fakeLog({ to, amountUnits, txHash, logIndex, blockHex }) {
    return {
        address: NETWORKS.base.usdc,
        topics: [TOPIC, '0x' + '0'.repeat(64), '0x' + to.replace(/^0x/, '').toLowerCase().padStart(64, '0')],
        data: '0x' + amountUnits.toString(16).padStart(64, '0'),
        transactionHash: txHash,
        logIndex,
        blockNumber: blockHex,
    };
}

function hex(n) { return '0x' + n.toString(16); }

// --- harness ---
let fetchScript; // { method: [results...] } — shift per call
let fetchCalls;  // captured { url, method }

function scriptFetch(map) {
    fetchScript = map;
    fetchCalls = [];
    let getLogsDelivered = false; // chunked catch-up windows re-call eth_getLogs; chunks after the first see no NEW logs
    global.fetch = jest.fn(async (url, opts) => {
        const method = JSON.parse(opts.body).method;
        fetchCalls.push({ url, method });
        const queue = fetchScript[method];
        if (!queue || queue.length === 0) {
            if (method === 'eth_getLogs' && getLogsDelivered) {
                return { ok: true, status: 200, json: async () => ({ jsonrpc: '2.0', id: 1, result: [] }) };
            }
            throw new Error('UNEXPECTED RPC CALL: ' + method);
        }
        if (method === 'eth_getLogs' && queue.length === 1 && getLogsDelivered) {
            return { ok: true, status: 200, json: async () => ({ jsonrpc: '2.0', id: 1, result: [] }) };
        }
        const result = queue.shift();
        if (method === 'eth_getLogs') getLogsDelivered = true;
        return { ok: true, status: 200, json: async () => ({ jsonrpc: '2.0', id: 1, result }) };
    });
}

function scriptDb(pairs) { // first matching needle wins; unknown SQL fails loudly
    CDB.db.query.mockImplementation(async (sql) => {
        for (const [needle, resp] of pairs) {
            if (sql.includes(needle)) {
                const v = resp();
                return v === undefined ? { rows: [] } : v;
            }
        }
        throw new Error('UNEXPECTED SQL in simulated suite: ' + sql.slice(0, 80));
    });
}

const mkReq = {
    post: (body = {}) => ({ method: 'POST', body, user: { id: USER_ID } }),
    get: (query = {}) => ({ method: 'GET', query, user: { id: USER_ID } }),
};
function mkRes() {
    const res = { code: null, body: null };
    res.status = jest.fn((c) => { res.code = c; return res; });
    res.json = jest.fn((b) => { res.body = b; return res; });
    return res;
}
async function call(router, method, path, req) {
    const layer = router.stack.find((l) => l.route && l.route.path === path && l.route.methods[method]);
    if (!layer) throw new Error('route missing: ' + method + ' ' + path);
    const res = mkRes();
    layer.route.stack[0].handle(req, res, () => {}); // authenticateToken mock sets req.user
    await layer.route.stack[layer.route.stack.length - 1].handle(req, res);
    return res;
}

